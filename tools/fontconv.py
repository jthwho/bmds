#!/usr/bin/env python3
# Converts a GNU Unifont-style .hex font (8x16 and 16x16 glyphs) into a BMDS
# Font in rodata (components/bmds_ui/include/bmds/font.h).
#
#   fontconv.py FONT.hex OUT.cpp NAME
#
# Controls (C0, DEL, C1) and the private use area are left out. Glyphs are
# grouped into runs of consecutive codepoints of one width.

import sys

def main():
        src, out, name = sys.argv[1:4]
        glyphs = {}
        for line in open(src):
                line = line.strip()
                if not line:
                        continue
                code, bits = line.split(':')
                cp = int(code, 16)
                if cp < 0x20 or 0x7f <= cp <= 0x9f or 0xe000 <= cp <= 0xf8ff:
                        continue
                if len(bits) not in (32, 64):
                        sys.exit(f'{src}: U+{cp:04X}: {len(bits)} hex digits')
                glyphs[cp] = bytes.fromhex(bits)
        replacement = next(cp for cp in (0xfffd, 0x25a1, 0x3f) if cp in glyphs)

        tables = {}
        for wide in (False, True):
                size = 32 if wide else 16
                ranges, data = [], bytearray()
                for cp in sorted(c for c, g in glyphs.items() if (len(g) == 32) == wide):
                        index = len(data) // size
                        if index > 0xffff:
                                sys.exit(f'{src}: too many glyphs for 16-bit indices')
                        if ranges and ranges[-1][0] + ranges[-1][1] == cp and ranges[-1][1] < 0xffff:
                                ranges[-1][1] += 1
                        else:
                                ranges.append([cp, 1, index])
                        data += glyphs[cp]
                tables[wide] = (ranges, data)

        with open(out, 'w') as f:
                f.write(f'// Generated by tools/fontconv.py from {src.split("/")[-1]}: do not edit.\n\n')
                f.write('#include <bmds/font.h>\n\nBMDS_NAMESPACE_BEGIN\n\nnamespace {\n\n')
                for wide in (False, True):
                        ranges, data = tables[wide]
                        kind = 'Wide' if wide else 'Narrow'
                        f.write(f'        constexpr Font::Range {kind}Ranges[] = {{\n')
                        for first, count, index in ranges:
                                f.write(f'                {{0x{first:05x}, {count}, {index}}},\n')
                        f.write('        };\n\n')
                        f.write(f'        constexpr uint8_t {kind}Bits[] = {{\n')
                        for i in range(0, len(data), 16):
                                row = ', '.join(f'0x{b:02x}' for b in data[i:i + 16])
                                f.write(f'                {row},\n')
                        f.write('        };\n\n')
                f.write('} // namespace\n\n')
                f.write(f'constinit const Font Fonts::{name}(8, 16, NarrowRanges, NarrowBits, WideRanges, WideBits,\n')
                f.write(f'                                     0x{replacement:x});\n\n')
                f.write('BMDS_NAMESPACE_END\n')
        n = sum(len(tables[w][0]) for w in tables)
        print(f'fontconv: {name}: {len(glyphs)} glyphs, {n} runs, '
              f'{len(tables[False][1]) + len(tables[True][1])} bytes of bitmaps')

main()

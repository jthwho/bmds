#!/usr/bin/env python3
# Embeds a directory's files in the firmware as a table (devplan/gui.md G14):
# each file's path (relative, '/'-separated) and bytes, sorted by path.
#
#   embedfiles.py SRC_DIR OUT_CPP HEADER NAMESPACE
#
# HEADER is included for the table's type, NAMESPACE's `File` (path, data,
# size), `files[]` and `count`. Files and directories starting with '.' are
# left out.
import os
import sys


def main():
    src, out, header, namespace = sys.argv[1:5]
    paths = []
    for root, dirs, files in os.walk(src):
        dirs[:] = sorted(d for d in dirs if not d.startswith("."))
        for name in sorted(files):
            if name.startswith("."):
                continue
            paths.append(os.path.relpath(os.path.join(root, name), src).replace(os.sep, "/"))
    paths.sort()
    lines = ["// Generated by tools/embedfiles.py from %s: do not edit." % os.path.basename(src.rstrip("/")),
             "#include <cstddef>", "#include <cstdint>", '#include "%s"' % header, "",
             "BMDS_NAMESPACE_BEGIN", "", "namespace {", ""]
    for i, rel in enumerate(paths):
        with open(os.path.join(src, rel), "rb") as f:
            data = f.read()
        body = ",".join(str(b) for b in data) if data else "0"
        lines.append("        constexpr uint8_t File%d[] = {%s};" % (i, body))
    lines += ["", "} // namespace", "",
              "const %s::File %s::files[] = {" % (namespace, namespace)]
    for i, rel in enumerate(paths):
        with open(os.path.join(src, rel), "rb") as f:
            size = len(f.read())
        lines.append('        {"%s", File%d, %d},' % (rel, i, size))
    if not paths:
        lines.append('        {"", nullptr, 0},')
    lines += ["};", "", "const size_t %s::count = %d;" % (namespace, len(paths)), "", "BMDS_NAMESPACE_END", ""]
    text = "\n".join(lines)
    try:
        with open(out) as f:
            if f.read() == text:
                return 0
    except OSError:
        pass
    with open(out, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())

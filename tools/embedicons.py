#!/usr/bin/env python3
# Writes a header with a built-in program's icons (devplan/gui.md §4j): PNG
# images as rodata and a `ProgramIcon` array named VAR for BMDS_PROGRAM_ICONS.
# Each PNG's size is read from its header.
#
#   embedicons.py OUT VAR PNG...
import os
import struct
import sys


def main():
    out, var, pngs = sys.argv[1], sys.argv[2], sys.argv[3:]
    lines = ["// Generated by tools/embedicons.py: do not edit.", "#pragma once", "#include <cstdint>",
             "#include <bmds/builtinprograms.h>", "", "namespace {", ""]
    entries = []
    for i, png in enumerate(pngs):
        with open(png, "rb") as f:
            data = f.read()
        if data[:8] != b"\x89PNG\r\n\x1a\n":
            sys.exit("embedicons: %s isn't a PNG (an LFS pointer? git lfs pull)" % png)
        width, height = struct.unpack(">II", data[16:24])
        lines.append("        // %s" % os.path.basename(png))
        lines.append("        constexpr uint8_t %sPng%d[] = {%s};" % (var, i, ",".join(str(b) for b in data)))
        entries.append("{%d, %d, %sPng%d, %d}" % (width, height, var, i, len(data)))
    lines += ["", "        constexpr ::bmds::ProgramIcon %s[] = {%s};" % (var, ", ".join(entries)), "", "} // namespace", ""]
    text = "\n".join(lines)
    try:
        if open(out).read() == text:
            return 0
    except OSError:
        pass
    with open(out, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
# Writes a C++ source with a register table read from ESP-IDF's generated
# register headers (soc/*_reg.h): each register's name and offset, each
# field's name, bits and access, for `display dsi` (devplan/display.md §5e).
# Names lose the block's prefix and are lower case.
#
#   gen-regtable.py OUT VAR PREFIX HEADER [NOREAD...]
#
# PREFIX is the block's (DSI_HOST_); NOREAD names registers a read changes
# (clear-on-read flags, a FIFO's head), which the dump must not touch.
import re
import sys

REG = re.compile(r"^#define (\w+)_REG \(DR_REG_\w+ \+ (0x[0-9a-fA-F]+)\)")
FIELD = re.compile(r"^/\*\* (\w+) : ([A-Z/]+); bitpos: \[(\d+)(?::(\d+))?\];")
ACCESS = {"RO": 0, "R/W": 1, "WT": 2}


def main():
    out, var, prefix, header, noread = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4], set(sys.argv[5:])
    regs = []
    with open(header) as f:
        for line in f:
            m = REG.match(line)
            if m:
                name = m.group(1)[len(prefix):].lower() if m.group(1).startswith(prefix) else m.group(1).lower()
                regs.append([name, int(m.group(2), 16), []])
                continue
            m = FIELD.match(line)
            if m and regs:
                name = m.group(1)[len(prefix):].lower() if m.group(1).startswith(prefix) else m.group(1).lower()
                hi = int(m.group(3))
                lo = int(m.group(4)) if m.group(4) is not None else hi
                regs[-1][2].append((name, lo, hi - lo + 1, ACCESS.get(m.group(2), 3)))
    if not regs:
        sys.exit("gen-regtable: no registers in %s" % header)
    unknown = noread - {r[0] for r in regs}
    if unknown:
        sys.exit("gen-regtable: %s: no register %s" % (header, ", ".join(sorted(unknown))))
    lines = ["// Generated by tools/gen-regtable.py from %s: do not edit." % header.split("/components/")[-1],
             "#include \"regtable.h\"", "", "BMDS_NAMESPACE_BEGIN", "", "namespace detail {", ""]
    fields, entries = [], []
    for name, offset, fs in regs:
        entries.append("        {\"%s\", 0x%03x, %d, %d, %s}," % (name, offset, len(fields), len(fs),
                                                              "true" if name in noread else "false"))
        for fname, lo, width, access in fs:
            fields.append("        {\"%s\", %d, %d, %d}," % (fname, lo, width, access))
    lines.append("constexpr RegField %sFields[] = {" % var)
    lines += fields
    lines += ["};", "", "constexpr RegInfo %sRegs[] = {" % var]
    lines += entries
    lines += ["};", "", "extern const RegTable %s;" % var,
              "constexpr RegTable %s = {%sRegs, sizeof(%sRegs) / sizeof(%sRegs[0]), %sFields};" % ((var,) * 5), "",
              "} // namespace detail", "", "BMDS_NAMESPACE_END", ""]
    text = "\n".join(lines)
    try:
        if open(out).read() == text:
            return 0
    except OSError:
        pass
    with open(out, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
